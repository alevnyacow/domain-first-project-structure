import path from 'node:path';
import { unitId } from '../agent-identifiers';
import {
    aggregatesOf,
    type BackendUnit,
    findBackendUnits,
    kindLayouts,
    moveBackendUnit,
    type UnitPlace,
    validateBackendMove
} from '../backend-module-move';
import { ConfigFile } from '../config-file';
import { discardPendingChanges, Folder } from '../file-system';
import {
    confirm,
    input,
    isNonInteractive,
    RequestError,
    report,
    Separator,
    select
} from '../interaction';
import { ProjectRoot } from '../project-root';

const noAggregate = 'No aggregate';

/**
 * Renames a unit of a bounded context or the Shared Kernel, or moves it
 * to another context or the Shared Kernel, with every file, name and
 * import that follows it.
 */
export const moveBackendUnitUseCase = async (ownerFolder: Folder) => {
    const root = new ProjectRoot().path;
    const rootFolderPath = path.join(
        root,
        ConfigFile.Instance.data.project.rootFolder
    );
    const sharedKernelPath = path.join(rootFolderPath, 'shared-kernel');
    const units = findBackendUnits(ownerFolder.path);
    if (!units.length) {
        report('No modules generated by df-scaffold were found here.');
        return;
    }

    const unit = await select<BackendUnit>({
        key: 'module',
        id: unitId,
        message: 'Module:',
        choices: Object.keys(kindLayouts).flatMap((kind) => {
            const group = units.filter((x) => x.kind === kind);
            return group.length
                ? [
                      new Separator(`── ${kindLayouts[group[0].kind].title}`),
                      ...group.map((value) => ({
                          name: value.aggregate
                              ? `${value.name} (${value.aggregate})`
                              : value.name,
                          value
                      }))
                  ]
                : [];
        }),
        pageSize: 20
    });

    const placeName = (ownerPath: string) =>
        ownerPath === sharedKernelPath
            ? 'Shared Kernel'
            : `Bounded Context: ${path.basename(ownerPath)}`;
    const contexts = new Folder(rootFolderPath)
        .subitem(['bounded-contexts'])
        .content.subfolderNames.map((name) =>
            path.join(rootFolderPath, 'bounded-contexts', name)
        );
    const places = [
        unit.ownerPath,
        ...contexts,
        ...(kindLayouts[unit.kind].sharedKernel ? [sharedKernelPath] : [])
    ].filter((place, index, all) => all.indexOf(place) === index);
    const ownerPath = await select({
        key: 'targetContext',
        id: (owner) =>
            owner === sharedKernelPath ? 'shared-kernel' : path.basename(owner),
        message: 'Move to:',
        choices: places.map((value) => ({
            name:
                value === unit.ownerPath
                    ? `${placeName(value)} (stays)`
                    : placeName(value),
            value
        }))
    });

    let aggregate: string | undefined;
    const aggregates =
        ownerPath === sharedKernelPath ? [] : aggregatesOf(ownerPath);
    if (
        (unit.kind === 'entity' || unit.kind === 'value-object') &&
        aggregates.length
    ) {
        const picked = await select({
            key: 'aggregate',
            message: 'Aggregate:',
            choices: [noAggregate, ...aggregates],
            default:
                ownerPath === unit.ownerPath && unit.aggregate
                    ? unit.aggregate
                    : noAggregate
        });
        aggregate = picked === noAggregate ? undefined : picked;
    }

    const target = (name: string): UnitPlace => ({
        ownerPath,
        aggregate,
        name: name.trim()
    });
    const name = await input({
        key: 'name',
        message: 'New name:',
        default: unit.name,
        validate: (value) =>
            validateBackendMove(unit, target(value), sharedKernelPath)
    });

    const result = moveBackendUnit(root, rootFolderPath, unit, target(name));
    if (result.violations) {
        if (isNonInteractive())
            throw new RequestError(
                'MOVE_NOT_ALLOWED',
                'The move would cross bounded-context boundaries.',
                { violations: result.violations }
            );
        report(
            [
                `Nothing was moved: these imports would cross a bounded context boundary.`,
                ...result.violations.map(([from, to]) => `  ${from} → ${to}`),
                'Give the other context its own query or command, or move what it depends on first.'
            ].join('\n')
        );
        return;
    }

    const relative = (file: string) => path.relative(root, file);
    report(
        [
            'Files to move:',
            ...result.moves.map(
                ([from, to]) => `  ${relative(from)} → ${relative(to)}`
            ),
            ...(result.updated.length
                ? [
                      'Files with updated imports and names:',
                      ...result.updated.map((file) => `  ${relative(file)}`)
                  ]
                : [])
        ].join('\n')
    );
    if (!(await confirm({ key: 'apply', message: 'Apply?', default: true }))) {
        discardPendingChanges();
        report('Cancelled: nothing was written.');
    }
};
