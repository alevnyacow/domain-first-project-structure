import fs from 'node:fs';
import path from 'node:path';
import { discardPendingChanges, type Folder } from '../file-system';
import { confirm, input, report, select } from '../interaction';
import { frameworkTitles, pageRouter } from '../page-router';
import { ProjectRoot } from '../project-root';
import {
    type FrontendFramework,
    findReactModules,
    frontendKindLayouts,
    moveReactModule,
    pageRouteFolder,
    type ReactModule,
    type ReactModuleKind,
    type RouteMove,
    reactKindTitles,
    routeFolder,
    validateMove
} from '../react-module-move';

/**
 * With Next.js or SvelteKit, a page's route at the same path
 * (`app/<name>/page.tsx`, `src/routes/<name>/+page.svelte`) can follow the
 * page. The URL changes with it, so it is asked.
 */
const promptRouteMove = async (
    root: string,
    page: ReactModule,
    newName: string,
    framework: FrontendFramework
): Promise<RouteMove | undefined> => {
    const router = pageRouter(framework);
    if (!router) return undefined;
    const appFolder = path.join(root, router.folder(root));
    const from = pageRouteFolder(appFolder, page, framework);
    const to = routeFolder(appFolder, newName);
    const relative = (file: string) =>
        path.relative(root, file).split(path.sep).join('/');
    // Only a route that renders this page belongs to it.
    if (!from || from === to) return undefined;
    if (fs.existsSync(path.join(to, router.pageFile))) {
        report(
            `${relative(to)}/${router.pageFile} already exists: the route ${relative(from)} stays.`
        );
        return undefined;
    }
    const move = await confirm({
        key: 'moveRoute',
        message: `Move the ${router.title} route too: ${relative(from)} → ${relative(to)}? Its URL changes.`,
        default: true
    });
    return move ? { appFolder, from, to } : undefined;
};

export const moveReactModuleUseCase = async (
    presentationReactFolder: Folder,
    kind: ReactModuleKind,
    framework: FrontendFramework = 'react'
) => {
    const reactFolder = presentationReactFolder.path;
    const modules = findReactModules(reactFolder, kind, framework);
    if (!modules.length) {
        report(
            `No ${reactKindTitles[kind][1]} generated by ${frameworkTitles[framework].cli} were found.`
        );
        return;
    }

    const module = await select({
        key: 'module',
        id: (value) => value.name,
        message: `${reactKindTitles[kind][0]}:`,
        choices: modules.map((value) => ({
            name: value.name,
            value,
            description: path.relative(reactFolder, value.path)
        }))
    });
    const name = await input({
        key: 'name',
        message: frontendKindLayouts(framework)[kind].nested
            ? 'New name (folders split by "/"):'
            : 'New name:',
        default: module.name,
        validate: (value) => validateMove(reactFolder, module, value, framework)
    });

    const root = new ProjectRoot().path;
    const relative = (file: string) =>
        path.relative(root, file).split(path.sep).join('/');
    const route =
        kind === 'page'
            ? await promptRouteMove(root, module, name, framework)
            : undefined;
    const { moves, updated } = moveReactModule(
        root,
        reactFolder,
        module,
        name,
        route,
        framework
    );
    if (!moves.length && !updated.length) {
        report('Nothing to change.');
        return;
    }

    report(
        [
            'Files to move:',
            ...moves.map(
                ([from, to]) => `  ${relative(from)} → ${relative(to)}`
            ),
            ...(updated.length
                ? [
                      'Files with updated imports:',
                      ...updated.map((file) => `  ${relative(file)}`)
                  ]
                : [])
        ].join('\n')
    );
    if (!(await confirm({ key: 'apply', message: 'Apply?', default: true }))) {
        discardPendingChanges();
        report('Cancelled: nothing was written.');
    }
};
