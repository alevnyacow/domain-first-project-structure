import path from 'node:path';
import { discardPendingChanges, type Folder } from '../file-system';
import { confirm, input, report, select } from '../interaction';
import { ProjectRoot } from '../project-root';
import {
    findReactModules,
    moveReactModule,
    type ReactModuleKind,
    validateMove
} from '../react-module-move';

export const moveReactModuleUseCase = async (
    presentationReactFolder: Folder,
    kind: ReactModuleKind
) => {
    const reactFolder = presentationReactFolder.path;
    const modules = findReactModules(reactFolder, kind);
    if (!modules.length) {
        report(`No ${kind}s generated by df-react were found.`);
        return;
    }

    const module = await select({
        key: 'module',
        id: (value) => value.name,
        message: kind === 'page' ? 'Page:' : 'Widget:',
        choices: modules.map((value) => ({
            name: value.name,
            value,
            description: path.relative(reactFolder, value.path)
        }))
    });
    const name = await input({
        key: 'name',
        message: 'New name (folders split by "/"):',
        default: module.name,
        validate: (value) => validateMove(reactFolder, module, value)
    });

    const root = new ProjectRoot().path;
    const { moves, updated } = moveReactModule(root, reactFolder, module, name);
    if (!moves.length && !updated.length) {
        report('Nothing to change.');
        return;
    }

    const relative = (file: string) => path.relative(root, file);
    report(
        [
            'Files to move:',
            ...moves.map(
                ([from, to]) => `  ${relative(from)} → ${relative(to)}`
            ),
            ...(updated.length
                ? [
                      'Files with updated imports:',
                      ...updated.map((file) => `  ${relative(file)}`)
                  ]
                : [])
        ].join('\n')
    );
    if (!(await confirm({ key: 'apply', message: 'Apply?', default: true }))) {
        discardPendingChanges();
        report('Cancelled: nothing was written.');
    }
};
