import path from 'node:path';
import { discardPendingChanges, type Folder } from '../file-system';
import {
    confirm,
    isNonInteractive,
    RequestError,
    report,
    select
} from '../interaction';
import { frameworkTitles, pageRouter } from '../page-router';
import { ProjectRoot } from '../project-root';
import {
    deleteReactModule,
    type FrontendFramework,
    findReactModules,
    frontendKindTitles,
    pageRouteFolder,
    type ReactModuleKind
} from '../react-module-move';

/**
 * Deletes a page or widget with its files once nothing else imports it.
 * With Next.js or SvelteKit, a page's own route can go with it: its URL
 * stops working, so it is asked.
 */
export const deleteReactModuleUseCase = async (
    presentationReactFolder: Folder,
    kind: ReactModuleKind,
    framework: FrontendFramework = 'react'
) => {
    const reactFolder = presentationReactFolder.path;
    const modules = findReactModules(reactFolder, kind, framework);
    if (!modules.length) {
        report(
            `No ${frontendKindTitles(framework)[kind][1]} generated by ${frameworkTitles[framework].cli} were found.`
        );
        return;
    }

    const module = await select({
        key: 'module',
        id: (value) => value.name,
        message: `${frontendKindTitles(framework)[kind][0]} to delete:`,
        choices: modules.map((value) => ({
            name: value.name,
            value,
            description: path.relative(reactFolder, value.path)
        }))
    });

    const root = new ProjectRoot().path;
    const relative = (file: string) =>
        path.relative(root, file).split(path.sep).join('/');
    const router = kind === 'page' ? pageRouter(framework) : undefined;
    const appFolder = router && path.join(root, router.folder(root));
    const routeFolder =
        router && appFolder
            ? pageRouteFolder(appFolder, module, framework)
            : undefined;
    const withRoute =
        !!routeFolder &&
        (await confirm({
            key: 'deleteRoute',
            message: `Delete its ${router?.title} route too: ${relative(routeFolder)}? Its URL stops working.`,
            default: true
        }));

    const result = deleteReactModule(
        root,
        reactFolder,
        module,
        withRoute && routeFolder && appFolder
            ? { appFolder, folder: routeFolder }
            : undefined,
        framework
    );
    if (result.usedBy) {
        if (isNonInteractive())
            throw new RequestError(
                'DELETE_NOT_ALLOWED',
                `Other files still use the ${kind}.`,
                { usedBy: result.usedBy }
            );
        report(
            [
                'Nothing was deleted: these files still use it.',
                ...result.usedBy.map(([file, used]) => `  ${file} → ${used}`),
                'Remove those uses first.'
            ].join('\n')
        );
        return;
    }

    report(
        [
            'Files to delete:',
            ...result.deleted.map((file) => `  ${relative(file)}`)
        ].join('\n')
    );
    if (
        !(await confirm({ key: 'apply', message: 'Delete?', default: false }))
    ) {
        discardPendingChanges();
        report('Cancelled: nothing was deleted.');
    }
};
