import path from 'node:path';
import { discardPendingChanges, type Folder } from '../file-system';
import {
    confirm,
    isNonInteractive,
    RequestError,
    report,
    select
} from '../interaction';
import { nextAppFolder, usesNext } from '../next-app';
import { ProjectRoot } from '../project-root';
import {
    deleteReactModule,
    findReactModules,
    pageRouteFolder,
    type ReactModuleKind
} from '../react-module-move';

/**
 * Deletes a page or widget with its files once nothing else imports it.
 * With Next.js, a page's own route can go with it: its URL stops working,
 * so it is asked.
 */
export const deleteReactModuleUseCase = async (
    presentationReactFolder: Folder,
    kind: ReactModuleKind
) => {
    const reactFolder = presentationReactFolder.path;
    const modules = findReactModules(reactFolder, kind);
    if (!modules.length) {
        report(`No ${kind}s generated by df-react were found.`);
        return;
    }

    const module = await select({
        key: 'module',
        id: (value) => value.name,
        message: kind === 'page' ? 'Page to delete:' : 'Widget to delete:',
        choices: modules.map((value) => ({
            name: value.name,
            value,
            description: path.relative(reactFolder, value.path)
        }))
    });

    const root = new ProjectRoot().path;
    const relative = (file: string) =>
        path.relative(root, file).split(path.sep).join('/');
    const appFolder = path.join(root, nextAppFolder(root));
    const routeFolder =
        kind === 'page' && usesNext()
            ? pageRouteFolder(appFolder, module)
            : undefined;
    const withRoute =
        !!routeFolder &&
        (await confirm({
            key: 'deleteRoute',
            message: `Delete its Next.js route too: ${relative(routeFolder)}? Its URL stops working.`,
            default: true
        }));

    const result = deleteReactModule(
        root,
        reactFolder,
        module,
        withRoute && routeFolder
            ? { appFolder, folder: routeFolder }
            : undefined
    );
    if (result.usedBy) {
        if (isNonInteractive())
            throw new RequestError(
                'DELETE_NOT_ALLOWED',
                `Other files still use the ${kind}.`,
                { usedBy: result.usedBy }
            );
        report(
            [
                'Nothing was deleted: these files still use it.',
                ...result.usedBy.map(([file, used]) => `  ${file} → ${used}`),
                'Remove those uses first.'
            ].join('\n')
        );
        return;
    }

    report(
        [
            'Files to delete:',
            ...result.deleted.map((file) => `  ${relative(file)}`)
        ].join('\n')
    );
    if (
        !(await confirm({ key: 'apply', message: 'Delete?', default: false }))
    ) {
        discardPendingChanges();
        report('Cancelled: nothing was deleted.');
    }
};
