import path from 'node:path';
import { unitId } from '../agent-identifiers';
import {
    type BackendUnit,
    deleteBackendUnit,
    findBackendUnits,
    kindLayouts
} from '../backend-module-move';
import { ConfigFile } from '../config-file';
import type { Folder } from '../file-system';
import { discardPendingChanges } from '../file-system';
import {
    confirm,
    isNonInteractive,
    RequestError,
    report,
    Separator,
    select
} from '../interaction';
import { ProjectRoot } from '../project-root';

/**
 * Deletes a unit of a bounded context or the Shared Kernel with every file
 * of it, once nothing else in the project imports it.
 */
export const deleteBackendUnitUseCase = async (ownerFolder: Folder) => {
    const root = new ProjectRoot().path;
    const rootFolderPath = path.join(
        root,
        ConfigFile.Instance.data.project.rootFolder
    );
    const units = findBackendUnits(ownerFolder.path);
    if (!units.length) {
        report('No modules generated by df-scaffold were found here.');
        return;
    }

    const unit = await select<BackendUnit>({
        key: 'module',
        id: unitId,
        message: 'Module to delete:',
        choices: Object.keys(kindLayouts).flatMap((kind) => {
            const group = units.filter((x) => x.kind === kind);
            return group.length
                ? [
                      new Separator(`── ${kindLayouts[group[0].kind].title}`),
                      ...group.map((value) => ({
                          name: value.aggregate
                              ? `${value.name} (${value.aggregate})`
                              : value.name,
                          value
                      }))
                  ]
                : [];
        }),
        pageSize: 20
    });

    const result = deleteBackendUnit(root, rootFolderPath, unit);
    if (result.usedBy) {
        if (isNonInteractive())
            throw new RequestError(
                'DELETE_NOT_ALLOWED',
                'Other files still use the module.',
                { usedBy: result.usedBy }
            );
        report(
            [
                'Nothing was deleted: these files still use it.',
                ...result.usedBy.map(([file, used]) => `  ${file} → ${used}`),
                'Remove those uses first (Wire dependency edits wiring; imports and constructor parameters are yours).'
            ].join('\n')
        );
        return;
    }

    const relative = (file: string) => path.relative(root, file);
    report(
        [
            'Files to delete:',
            ...result.deleted.map((file) => `  ${relative(file)}`),
            ...(result.updated.length
                ? [
                      'Files to update:',
                      ...result.updated.map((file) => `  ${relative(file)}`)
                  ]
                : [])
        ].join('\n')
    );
    if (
        !(await confirm({ key: 'apply', message: 'Delete?', default: false }))
    ) {
        discardPendingChanges();
        report('Cancelled: nothing was deleted.');
    }
};
